// Minimal i18n: a reactive locale + t(key) lookup over two dictionaries.
// Kept dependency-free on purpose (no vue-i18n) to stay lightweight.
import { ref } from 'vue'

export type Locale = 'zh' | 'en'

const STORAGE_KEY = 'worktools.locale'

export const locale = ref<Locale>(readStored())

function readStored(): Locale {
  try {
    const v = localStorage.getItem(STORAGE_KEY)
    return v === 'en' ? 'en' : 'zh'
  } catch {
    return 'zh'
  }
}

export function setLocale(l: Locale) {
  locale.value = l
  try {
    localStorage.setItem(STORAGE_KEY, l)
  } catch {
    /* ignore */
  }
}

