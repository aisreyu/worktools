// errText maps a backend error (machine code like "cron_empty" or
// "k8s_bad_unit:Mi") to localized text. Unknown errors pass through as-is.
export function errText(e: unknown): string {
  const raw = e instanceof Error ? e.message : String(e)
  const i = raw.indexOf(':')
  const code = i > 0 ? raw.slice(0, i) : raw
  const rest = i > 0 ? raw.slice(i + 1) : ''
  const key = 'err.' + code
  if (dicts[locale.value][key] || zh[key]) {
    return t(key, { v: rest })
  }
  return raw
}

// detailText maps a backend detail code (password audit findings, k8s notes)
// like "reused:3" to localized text.
export function detailText(raw: string): string {
  if (!raw) return raw
  const i = raw.indexOf(':')
  const code = i > 0 ? raw.slice(0, i) : raw
  const rest = i > 0 ? raw.slice(i + 1) : ''
  const key = 'auditDetail.' + code
  if (dicts[locale.value][key] || zh[key]) {
    return t(key, { n: rest })
  }
  return raw
}

// cronDescText maps a cron description code like "every_day:09:00" or
// "weekly:1:09:30" to localized human-readable text.
export function cronDescText(code: string): string {
  if (!code) return ''
  const parts = code.split(':')
  const kind = parts[0]
  const key = 'cronDesc.' + kind
  if (!(dicts[locale.value][key] || zh[key])) return code
  const params: Record<string, string> = {}
  if (kind === 'hourly') params.m = parts[1] ?? ''
  else if (kind === 'every_day' || kind === 'every_weekday') {
    params.h = parts[1] ?? ''
    params.m = parts[2] ?? ''
  } else if (kind === 'weekly') {
    params.d = weekdayName(parts[1])
    params.h = parts[2] ?? ''
    params.m = parts[3] ?? ''
  } else if (kind === 'monthly') {
    params.dom = parts[1] ?? ''
    params.h = parts[2] ?? ''
    params.m = parts[3] ?? ''
  } else if (kind === 'yearly') {
    params.mon = parts[1] ?? ''
    params.dom = parts[2] ?? ''
    params.h = parts[3] ?? ''
    params.m = parts[4] ?? ''
  }
  return t(key, params)
}

function weekdayName(v: string): string {
  const n = Number(v)
  if (!Number.isInteger(n) || n < 0 || n > 6) return v
  return t('toolbox.dow' + n)
}

